const AudioTrack = require('../../models/AudioTrack');
const Subtitle = require('../../models/Subtitle');
const Video = require('../../models/Video');
const storageService = require('../storage.service');
const notificationService = require('../notification.service');
const { emitToUser } = require('../../sockets/notification.socket');
const { SUPPORTED_LANGS } = require('../../utils/constants');
const { transcribe } = require('./speechToText.service');
const { translateSegments } = require('./translation.service');
const { synthesizeSegments } = require('./textToSpeech.service');
const { mediaUrlForAI } = require('./aiClient');

const langLabel = (code) => SUPPORTED_LANGS.find((l) => l.code === code)?.name || code;

// ── Phụ đề WebVTT ────────────────────────────────────────────────────────────
const vttTime = (sec) => {
  const ms = Math.max(0, Math.round(sec * 1000));
  const h = String(Math.floor(ms / 3600000)).padStart(2, '0');
  const m = String(Math.floor((ms % 3600000) / 60000)).padStart(2, '0');
  const s = String(Math.floor((ms % 60000) / 1000)).padStart(2, '0');
  return `${h}:${m}:${s}.${String(ms % 1000).padStart(3, '0')}`;
};
const buildVtt = (segments, key = 'text') =>
  'WEBVTT\n\n' +
  segments
    .filter((s) => s[key])
    .map((s, i) => `${i + 1}\n${vttTime(s.start)} --> ${vttTime(Math.max(s.end, s.start + 0.5))}\n${s[key]}\n`)
    .join('\n');

async function saveSubtitle(videoId, lang, segments, key) {
  const url = await storageService.uploadBuffer(
    `${videoId}/subtitles/${lang}-${Date.now()}.vtt`,
    Buffer.from(buildVtt(segments, key), 'utf8'),
    'text/vtt; charset=utf-8',
    storageService.BUCKETS.AUDIO,
    storageService.IMMUTABLE_CACHE
  );
  await Subtitle.findOneAndUpdate(
    { videoId, lang },
    { url, format: 'vtt', langLabel: langLabel(lang), isAutoGenerated: true },
    { upsert: true, new: true, setDefaultsOnInsert: true }
  );
  return url;
}

/**
 * Pipeline lồng tiếng:
 *   video (bản nén 720p nếu có, không thì file gốc)
 *     → Whisper nhận dạng lời thoại + mốc thời gian   (AI /transcribe)
 *     → NLLB dịch từng segment                        (AI /translate)
 *     → phụ đề VTT gốc + bản dịch                      (backend tự tạo)
 *     → edge-tts đọc bản dịch, khớp thời lượng          (AI /tts)
 *     → upload mp3 lên MinIO; frontend phát audio này thay tiếng gốc
 */
exports.runDubbingPipeline = async (audioTrackId, onProgress) => {
  const track = await AudioTrack.findById(audioTrackId);
  if (!track) throw new Error('AudioTrack not found');
  const video = await Video.findById(track.videoId);
  if (!video) throw new Error('Video not found');

  const report = async (status, percent, message) => {
    track.status = status;
    await track.save();
    onProgress?.(percent, message);
    emitToUser(video.userId, 'dubbing:progress', {
      trackId: String(track._id),
      videoId: String(video._id),
      targetLang: track.targetLang,
      status,
      progress: percent,
      message,
    });
  };

  try {
    const mediaUrl = video.hlsUrl && !video.hlsUrl.endsWith('.m3u8') ? video.hlsUrl : video.originalUrl;
    if (!mediaUrl) throw new Error('Video này không có file MP4 để lồng tiếng (video mẫu dạng HLS chưa hỗ trợ)');

    // 1. Nhận dạng lời thoại
    await report('transcribing', 10, 'Đang nhận dạng lời thoại');
    const stt = await transcribe(mediaUrlForAI(mediaUrl), track.sourceLang);
    if (!stt.segments.length) throw new Error('Không nhận dạng được lời thoại trong video');
    track.transcript = stt.text;
    if (stt.model) track.modelVersion = stt.model;
    await track.save();
    await saveSubtitle(video._id, track.sourceLang, stt.segments, 'text').catch((err) =>
      console.warn('[dubbing] Lưu phụ đề gốc thất bại:', err.message)
    );

    // 2. Dịch
    await report('translating', 40, `Đang dịch sang ${langLabel(track.targetLang)}`);
    const translated = await translateSegments(stt.segments, track.sourceLang, track.targetLang);
    track.translatedText = translated.map((s) => s.translatedText).join(' ');
    track.subtitleUrl = await saveSubtitle(video._id, track.targetLang, translated, 'translatedText');
    await track.save();

    // 3. Đọc bản dịch
    await report('synthesizing', 65, 'Đang tổng hợp giọng nói');
    const totalSec = (video.durationMs || 0) / 1000 || stt.duration;
    const tts = await synthesizeSegments(translated, track.targetLang, totalSec);
    if (tts.buffer) {
      track.audioUrl = await storageService.uploadBuffer(
        `${video._id}/dubbed/${track.targetLang}-${Date.now()}.${tts.format}`,
        tts.buffer,
        tts.format === 'mp3' ? 'audio/mpeg' : undefined,
        storageService.BUCKETS.AUDIO,
        storageService.IMMUTABLE_CACHE
      );
    }

    track.error = null;
    await report('done', 100, 'Hoàn tất');
    await Video.findByIdAndUpdate(video._id, { $addToSet: { audioTracks: track._id } });

    await notificationService
      .createNotification(video.userId, 'dubbing_done', {
        videoId: video._id,
        videoThumbnail: video.thumbnailUrl,
        message: `Video của bạn đã có bản lồng tiếng ${langLabel(track.targetLang)}`,
      })
      .catch(() => {});

    return track;
  } catch (err) {
    track.status = 'failed';
    track.error = err.message;
    await track.save();
    emitToUser(video.userId, 'dubbing:progress', {
      trackId: String(track._id),
      videoId: String(video._id),
      targetLang: track.targetLang,
      status: 'failed',
      progress: 100,
      message: err.message,
    });
    throw err;
  }
};

exports.buildVtt = buildVtt;
